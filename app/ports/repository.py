"""RepositoryPort 协议 — 状态持久化边界（Swap：SQLite 现在 / PostgreSQL 未来）。"""

from __future__ import annotations

from typing import Any, Protocol, runtime_checkable

from ..domain.models import (
    AgentRegistryRecord,
    RunRecord,
    StepRecord,
    TaskPlan,
    TaskRecord,
)


@runtime_checkable
class RepositoryPort(Protocol):
    # --- Run ---
    async def create_run(self, run: RunRecord) -> RunRecord: ...
    async def get_run(self, run_id: str) -> RunRecord | None: ...
    async def update_run(self, run: RunRecord) -> RunRecord: ...
    async def list_runs(self, *, status: str | None = None, limit: int = 50) -> list[RunRecord]: ...
    async def list_active_runs(self) -> list[RunRecord]:
        """找回运行中/等待中的 Run（进程重启恢复用）。"""
        ...

    # --- Plan ---
    async def save_plan(self, run_id: str, plan: TaskPlan) -> TaskPlan: ...
    async def get_latest_plan(self, run_id: str) -> TaskPlan | None: ...

    # --- Task ---
    async def save_tasks(self, run_id: str, tasks: list[TaskRecord]) -> None: ...
    async def get_task(self, run_id: str, task_id: str) -> TaskRecord | None: ...
    async def list_tasks(self, run_id: str) -> list[TaskRecord]: ...
    async def update_task(self, task: TaskRecord) -> TaskRecord: ...
    async def task_successors(self, run_id: str, task_id: str) -> list[TaskRecord]:
        ...

    # --- Step (execution log) ---
    async def append_step(self, step: StepRecord) -> StepRecord: ...
    async def list_steps(self, run_id: str, *, task_id: str | None = None) -> list[StepRecord]: ...

    # --- Events ---
    async def append_event(self, *, run_id: str, event_type: str, task_id: str | None,
                           payload: dict[str, Any]) -> None: ...
    async def list_events(self, run_id: str) -> list[dict[str, Any]]: ...

    # --- Agent Registry ---
    async def register(self, record: AgentRegistryRecord) -> AgentRegistryRecord: ...
    async def deregister(self, agent_id: str) -> None: ...
    async def get_agent(self, agent_id: str) -> AgentRegistryRecord | None: ...
    async def list_agents(self, *, skill: str | None = None, status: str | None = None) -> list[AgentRegistryRecord]: ...
    async def update_agent(self, record: AgentRegistryRecord) -> AgentRegistryRecord: ...

    # --- Tool call idempotency ---
    async def tool_call_has_run(self, idempotency_key: str) -> bool: ...
    async def record_tool_call(self, *, idempotency_key: str, task_id: str | None,
                               tool_name: str, status: str, result: dict[str, Any] | None,
                               error: dict[str, Any] | None) -> None: ...

    # --- A2A tracking ---
    async def upsert_a2a_task(self, *, a2a_task_id: str, run_id: str, task_id: str,
                              agent_id: str, status: str, message: dict[str, Any],
                              artifacts: list[dict[str, Any]],
                              error: dict[str, Any] | None) -> None: ...
    async def get_a2a_task(self, run_id: str, task_id: str) -> dict[str, Any] | None: ...